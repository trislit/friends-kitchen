import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { RF, parseChanceGame, maximumPrize, expectedReward } from "@rarefriends/friendsdk/game";
import { ANNOYED_MS, BREAK_MS, EXIT_MS, FAST_TIP_BPS, FRESH_MS, JAR_FAST_BONUS_BPS, LAMP_BONUS_MS, LUCKY_TIP_BPS, PATIENCE_MS, RECIPES, SPOIL_MS, STARTER, breakFor, buyIngredient, buyUpgrade, createCustomer, customerForDish, customerLine, customerMood, customerName, freshness, holdTimes, patienceFor, payment, plateMatches, priceOf, recipeForRoll, recipeFromPlate, rollTip, servePay, tipValue, waveSize } from "../game/service.mjs";

const kitchenJSON = JSON.parse(await readFile(new URL("../game/game.json", import.meta.url)));
const kitchen = parseChanceGame(kitchenJSON);

test("the dish menu matches customer orders", () => {
  assert.equal(maximumPrize(kitchen), 12n * RF);
  assert.equal(expectedReward(kitchen), 252n * RF / 100n);
  assert.deepEqual(kitchen.outcomes.map(item => item.name), RECIPES.map(item => item.name));
  assert.deepEqual(kitchen.outcomes.map(item => item.reward), RECIPES.map(item => item.pay));
  assert.deepEqual(kitchen.outcomes.map(item => item.chanceBps), [2800, 2200, 1600, 1200, 1000, 700, 300, 200]);
});

test("a matching plate pays the full tab and a wrong plate pays a quarter", () => {
  const toast = RECIPES[0];
  assert.equal(plateMatches(["butter", "bread"], toast.ingredients), true);
  assert.deepEqual(payment(["bread", "butter"], toast), { correct: true, amount: RF });
  assert.deepEqual(payment(["bread"], toast), { correct: false, amount: RF / 4n });
  assert.deepEqual(payment(["bread", "butter", "spice"], toast), { correct: false, amount: RF / 4n });
  const tea = RECIPES[1];
  assert.equal(payment(["tea"], tea).amount, 3n * RF / 2n);
  assert.equal(payment([], tea).amount, 3n * RF / 8n);
});

test("ingredients are bought one at a time from dish cash", () => {
  assert.equal(recipeForRoll(0).name, "Toast");
  assert.equal(recipeForRoll(27).name, "Toast");
  assert.equal(recipeForRoll(28).name, "Garden Tea");
  assert.equal(recipeForRoll(99).name, "Signature Special");
  assert.throws(() => recipeForRoll(100));
  assert.ok(RECIPES.every(recipe => recipe.ingredients.every(id => (STARTER[id] ?? 0) >= 1)));
  assert.equal(priceOf("bread"), RF / 2n);
  assert.equal(priceOf("noodles"), RF);
  const broke = buyIngredient(0n, { bread: 0 }, "bread");
  assert.equal(broke.ok, false);
  assert.equal(broke.stock.bread, 0);
  const first = buyIngredient(RF, { bread: 1 }, "bread");
  const second = buyIngredient(first.cash, first.stock, "bread");
  assert.equal(second.ok, true);
  assert.equal(second.stock.bread, 3);
  assert.equal(second.cash, 0n);
  const toast = RECIPES[0];
  const replacement = toast.ingredients.reduce((sum, id) => sum + priceOf(id), 0n);
  assert.ok(replacement > toast.pay / 4n);
  assert.ok(replacement <= toast.pay);
  assert.equal(recipeFromPlate(["butter", "bread"])?.name, "Toast");
  assert.equal(recipeFromPlate(["bread"]), null);
  assert.equal(freshness(0), "fresh");
  assert.equal(freshness(FRESH_MS - 1), "fresh");
  assert.equal(freshness(FRESH_MS), "turning");
  assert.equal(freshness(SPOIL_MS), "spoiled");
  assert.deepEqual(holdTimes(0), { freshMs: FRESH_MS, spoilMs: SPOIL_MS });
  assert.equal(holdTimes(2).freshMs, FRESH_MS + 2 * LAMP_BONUS_MS);
  assert.equal(freshness(FRESH_MS, 1), "fresh");
  assert.equal(freshness(FRESH_MS + LAMP_BONUS_MS, 1), "turning");
  const noLamp = buyUpgrade(0n, { lamp: 0, jar: 0 }, "lamp");
  assert.equal(noLamp.ok, false);
  const lamp = buyUpgrade(2n * RF, { lamp: 0, jar: 0 }, "lamp");
  assert.equal(lamp.ok, true);
  assert.equal(lamp.owned.lamp, 1);
  assert.equal(lamp.cash, 0n);
  assert.equal(buyUpgrade(2n * RF, { lamp: 2, jar: 0 }, "lamp").ok, false);
  const jar = buyUpgrade(2n * RF, { lamp: 0, jar: 0 }, "jar");
  assert.equal(jar.owned.jar, 1);
  assert.equal(buyUpgrade(2n * RF, jar.owned, "jar").ok, false);
  assert.deepEqual(servePay("Toast", "Toast", "fresh"), { correct: true, state: "fresh", amount: RF });
  assert.equal(servePay("Toast", "Toast", "turning").amount, RF / 2n);
  assert.equal(servePay("Toast", "Garden Tea", "fresh").amount, 3n * RF / 8n);
  assert.equal(servePay("Toast", "Toast", "spoiled").amount, 0n);
  assert.equal(new Set(PATIENCE_MS).size, PATIENCE_MS.length);
  assert.notEqual(patienceFor(0), patienceFor(1));
  assert.equal(customerMood(0, patienceFor(0)), "waiting");
  assert.equal(customerMood(patienceFor(0) - ANNOYED_MS, patienceFor(0)), "annoyed");
  assert.equal(customerMood(patienceFor(0), patienceFor(0)), "leaving");
  assert.equal(customerMood(patienceFor(0) + EXIT_MS, patienceFor(0)), "gone");
  assert.equal(customerLine("Toast", "waiting", 0), "I'll have the Toast!");
  assert.equal(customerLine("Curry", "annoyed", 1), "Still no Curry?");
  assert.equal(customerLine("Toast", "leaving", 0), "I'm outta here. You're too slow.");
  const quick = { correct: true, state: "fresh", mood: "waiting" };
  assert.equal(rollTip(0, quick), "fast");
  assert.equal(rollTip(FAST_TIP_BPS, quick), "none");
  assert.equal(rollTip(FAST_TIP_BPS, quick, true), "fast");
  assert.equal(rollTip(FAST_TIP_BPS + JAR_FAST_BONUS_BPS, quick, true), "none");
  assert.equal(rollTip(LUCKY_TIP_BPS, { correct: true, state: "turning", mood: "annoyed" }, true), "lucky");
  assert.equal(rollTip(0, { correct: true, state: "fresh", mood: "annoyed" }), "lucky");
  assert.equal(rollTip(LUCKY_TIP_BPS, { correct: true, state: "turning", mood: "annoyed" }), "none");
  assert.equal(rollTip(0, { correct: false, state: "fresh", mood: "waiting" }), "none");
  assert.equal(tipValue(RF, "fast"), RF / 2n);
  assert.equal(tipValue(RF, "lucky"), RF / 4n);
  assert.equal(tipValue(RF, "none"), 0n);
  assert.equal(customerName(0, []), "Ada");
  assert.equal(customerName(0, ["Ada"]), "Jules");
  const early = createCustomer(0, 0, 1, 0);
  const later = createCustomer(0, 1, 2, 10, [early.name]);
  assert.equal(customerForDish([later, early], "Toast", 10)?.id, 1);
  assert.equal(customerForDish([later], "Garden Tea", 10), null);
  assert.deepEqual(waveSize(0), { size: 5, rush: true });
  assert.deepEqual(waveSize(20), { size: 2, rush: false });
  assert.deepEqual(waveSize(60), { size: 3, rush: false });
  assert.ok(BREAK_MS.includes(breakFor(0)));
  assert.ok(breakFor(0) >= 20_000);
});
